package tools;

public class clac {
    public int add(int n1, int n2)
    {
        return n1+n2;
    }
    public int pro(int n1, int n2)
    {
        return n1*n2;
    }
    public int quot(int n1, int n2)
    {
        return n1/n2;
    }
    public int sub(int n1, int n2)
    {
        return n1-n2;
    }

}
